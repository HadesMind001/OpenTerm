describe('ws binary framing (generated by the Python backend)', () => {
  it('decodes a small FRAME_EVENT', () => {
    const { type, topic, payload } = decodeBinaryFrame(b64(SMALL_EVENT))
    expect(type).toBe(FRAME_EVENT)
    expect(topic).toBe('tick:CRYPTO:BTCUSDT')
    expect(payload).toMatchObject({ price: 65000.5, size: 0.25, side: 'buy' })
  })

  it('decodes a >1 KiB payload the backend flipped to FRAME_COMPRESSED_EVENT', () => {
    // This is THE regression test for the ws.ts bug where compressed frames
    // (every depth snapshot) were decoded and then silently dropped because
    // the switch only forwarded FRAME_EVENT.
    const { type, topic, payload } = decodeBinaryFrame(b64(COMPRESSED_DEPTH))
    expect(type).toBe(FRAME_COMPRESSED_EVENT)
    expect(topic).toBe('depth:CRYPTO:BTCUSDT')
    const p = payload as { bids: unknown[]; asks: unknown[] }
    expect(p.bids).toHaveLength(20)
    expect(p.asks).toHaveLength(200)
  })

  it('rejects absurd topic lengths before trusting the u32', () => {
    const bad = new Uint8Array(64)
    const view = new DataView(bad.buffer)
    view.setUint8(0, FRAME_EVENT)
    view.setUint32(1, 0xffffffff) // "topic is 4 GiB long" — no.
    expect(() => decodeBinaryFrame(bad.buffer)).toThrow()
  })

  it('rejects truncated frames', () => {
    expect(() => decodeBinaryFrame(new Uint8Array([1, 0, 0]).buffer)).toThrow()
  })
})
