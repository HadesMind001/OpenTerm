// ── WIRE CONTRACT TEST ───────────────────────────────────────────────────
// The fixtures below are base64 of bytes produced by the REAL Python encoder
// (backend/openterm/api/ws_codec.py::encode_event), not hand-crafted here.
// That makes this the only test in the repo that pins the cross-language
// contract: if either side changes framing (endianness, msgpack flavor, the
// zstd threshold), this file fails for both of us. Regenerate with:
//   .venv/bin/python - <<'PY'
//   import sys, base64; sys.path.insert(0,'backend')
//   from openterm.api.ws_codec import encode_event
//   print(base64.b64encode(encode_event('tick:X', {'a':1})).decode())
//   PY

function b64(s: string): ArrayBuffer {
  const bin = atob(s)
  const buf = new Uint8Array(bin.length)
  for (let i = 0; i < bin.length; i++) buf[i] = bin.charCodeAt(i)
  return buf.buffer
}

